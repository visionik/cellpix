"""Generate src/pixcell/_diacritics.py: the row/column diacritics for Kitty's Unicode
placeholders.

Kitty's graphics protocol numbers placeholder rows and columns with combining marks:
the combining characters of class 230 (drawn above) in Unicode 6.0.0 that have no
decomposition, minus a few that normalization can fuse with a base letter. This builds
that list straight from the Unicode Character Database, so it's ours to license.

    uv run python tools/gen_diacritics.py
"""

from __future__ import annotations

import urllib.request
from pathlib import Path

URL = "https://www.unicode.org/Public/6.0.0/ucd/UnicodeData.txt"
# Combining marks normalization may fuse with a preceding letter (e.g. A + U+0300 -> À).
EXCLUDED = {
    0x0300, 0x0301, 0x0302, 0x0303, 0x0304, 0x0306, 0x0307, 0x0308, 0x0309, 0x030A,
    0x030B, 0x030C, 0x030F, 0x0311, 0x0313, 0x0314, 0x0342, 0x0653, 0x0654,
}
OUT = Path(__file__).resolve().parent.parent / "src" / "pixcell" / "_diacritics.py"


def diacritics(unicode_data: str) -> list[int]:
    found = []
    for line in unicode_data.splitlines():
        fields = line.split(";")
        # code;name;category;combining class;bidi;decomposition;...
        if len(fields) > 5 and fields[2] == "Mn" and fields[3] == "230" and fields[4] == "NSM" and not fields[5]:
            code = int(fields[0], 16)
            if code not in EXCLUDED:
                found.append(code)
    return found


def main() -> None:
    with urllib.request.urlopen(URL, timeout=60) as response:
        codes = diacritics(response.read().decode("utf-8"))
    rows = ",\n".join(
        "    " + ", ".join(f"0x{code:04X}" for code in codes[i : i + 8]) for i in range(0, len(codes), 8)
    )
    OUT.write_text(
        '"""Row/column diacritics for Kitty Unicode placeholders (generated by\n'
        'tools/gen_diacritics.py from the Unicode 6.0.0 Character Database). Index = number."""\n\n'
        f"DIACRITICS: tuple[int, ...] = (\n{rows},\n)\n"
    )
    print(f"{len(codes)} diacritics -> {OUT}")


if __name__ == "__main__":
    main()
